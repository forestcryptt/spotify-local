import fs from 'node:fs';
import { Track, SortingRule, TargetPlaylist } from '../api/types.js';
import { defaultGenreMapper, CANONICAL_GENRES } from './genre-mapper.js';
import { config } from '../config.js';

export type SortMode = 'genre' | 'decade' | 'artist' | 'rules';

export interface SorterOptions {
  mode: SortMode;
  prefix?: string;
  minTracks?: number;
  multiAssign?: boolean;
  rulesFilePath?: string;
  allowUnsorted?: boolean;
}

export interface SortingResult {
  mode: SortMode;
  playlists: TargetPlaylist[];
  totalTracks: number;
  assignedTracksCount: number;
  unassignedTracks: Track[];
}

export class MusicSorter {
  sort(tracks: Track[], options: SorterOptions): SortingResult {
    const mode = options.mode;
    const prefix = options.prefix ?? config.defaultPrefix;
    const minTracks = options.minTracks ?? 5;

    let targetPlaylists: TargetPlaylist[] = [];

    switch (mode) {
      case 'genre':
        targetPlaylists = this.sortByGenre(tracks, prefix);
        break;
      case 'decade':
        targetPlaylists = this.sortByDecade(tracks, prefix);
        break;
      case 'artist':
        targetPlaylists = this.sortByArtist(tracks, prefix, minTracks);
        break;
      case 'rules':
        targetPlaylists = this.sortByRules(tracks, prefix, options.rulesFilePath);
        break;
      default:
        throw new Error(`Unsupported sort mode: ${mode}`);
    }

    // Filter by minTracks
    const filteredPlaylists = targetPlaylists.filter((p) => p.tracks.length >= minTracks);

    // Track coverage calculation
    const assignedTrackUris = new Set<string>();
    for (const p of filteredPlaylists) {
      for (const t of p.tracks) {
        assignedTrackUris.add(t.uri);
      }
    }

    const unassigned = tracks.filter((t) => !assignedTrackUris.has(t.uri));

    return {
      mode,
      playlists: filteredPlaylists,
      totalTracks: tracks.length,
      assignedTracksCount: assignedTrackUris.size,
      unassignedTracks: unassigned,
    };
  }

  private sortByGenre(tracks: Track[], prefix: string): TargetPlaylist[] {
    const playlistMap = new Map<string, { desc: string; tracks: Track[] }>();

    for (const cat of CANONICAL_GENRES) {
      playlistMap.set(cat.name, { desc: `${cat.description} • Auto-generated`, tracks: [] });
    }

    for (const track of tracks) {
      const matched = defaultGenreMapper.classifyGenres(track.genres);
      track.matchedGenres = matched;

      for (const genreName of matched) {
        const item = playlistMap.get(genreName);
        if (item) {
          item.tracks.push(track);
        }
      }
    }

    const playlists: TargetPlaylist[] = [];
    for (const [name, data] of playlistMap.entries()) {
      if (data.tracks.length > 0) {
        playlists.push({
          name: `${prefix}${name}`,
          description: data.desc,
          tracks: data.tracks,
          trackUris: data.tracks.map((t) => t.uri),
        });
      }
    }

    // Sort playlists by track count descending
    return playlists.sort((a, b) => b.tracks.length - a.tracks.length);
  }

  private sortByDecade(tracks: Track[], prefix: string): TargetPlaylist[] {
    const decadeMap = new Map<string, Track[]>();

    for (const track of tracks) {
      const decade = track.decade || 'Classic & Vintage';
      if (!decadeMap.has(decade)) {
        decadeMap.set(decade, []);
      }
      decadeMap.get(decade)!.push(track);
    }

    const playlists: TargetPlaylist[] = [];
    // Sort decades chronologically
    const sortedDecades = Array.from(decadeMap.keys()).sort((a, b) => a.localeCompare(b));

    for (const decade of sortedDecades) {
      const decadeTracks = decadeMap.get(decade)!;
      playlists.push({
        name: `${prefix}${decade} Hits`,
        description: `Tracks from the ${decade} • Auto-generated by spotify-local`,
        tracks: decadeTracks,
        trackUris: decadeTracks.map((t) => t.uri),
      });
    }

    return playlists;
  }

  private sortByArtist(tracks: Track[], prefix: string, minTracks: number): TargetPlaylist[] {
    const artistMap = new Map<string, Track[]>();

    for (const track of tracks) {
      const artist = track.primaryArtist;
      if (!artistMap.has(artist)) {
        artistMap.set(artist, []);
      }
      artistMap.get(artist)!.push(track);
    }

    const playlists: TargetPlaylist[] = [];
    for (const [artist, artistTracks] of artistMap.entries()) {
      if (artistTracks.length >= minTracks) {
        playlists.push({
          name: `${prefix}Artist: ${artist}`,
          description: `All your saved tracks by ${artist} • Auto-generated`,
          tracks: artistTracks,
          trackUris: artistTracks.map((t) => t.uri),
        });
      }
    }

    return playlists.sort((a, b) => b.tracks.length - a.tracks.length);
  }

  private sortByRules(tracks: Track[], prefix: string, customRulesPath?: string): TargetPlaylist[] {
    const rulesPath = customRulesPath || config.rulesFile;
    if (!fs.existsSync(rulesPath)) {
      throw new Error(`Rules file not found at: ${rulesPath}`);
    }

    const rulesContent = fs.readFileSync(rulesPath, 'utf-8');
    const rules = JSON.parse(rulesContent) as SortingRule[];

    const playlists: TargetPlaylist[] = [];

    for (const rule of rules) {
      const matchedTracks: Track[] = [];

      for (const track of tracks) {
        let isMatch = false;

        // Check genre rules
        if (rule.genres && rule.genres.length > 0) {
          const trackGenres = track.genres.map((g) => g.toLowerCase());
          const hasGenreMatch = rule.genres.some((rg) =>
            trackGenres.some((tg) => tg.includes(rg.toLowerCase()))
          );
          if (hasGenreMatch) isMatch = true;
        }

        // Check artist rules
        if (!isMatch && rule.artists && rule.artists.length > 0) {
          const artistNames = track.artists.map((a) => a.name.toLowerCase());
          const hasArtistMatch = rule.artists.some((ra) =>
            artistNames.some((an) => an.includes(ra.toLowerCase()))
          );
          if (hasArtistMatch) isMatch = true;
        }

        // Check keyword rules (in track or album title)
        if (!isMatch && rule.keywords && rule.keywords.length > 0) {
          const targetStr = `${track.name} ${track.album}`.toLowerCase();
          const hasKeywordMatch = rule.keywords.some((kw) => targetStr.includes(kw.toLowerCase()));
          if (hasKeywordMatch) isMatch = true;
        }

        // Check decade / year range
        if (rule.decade && track.year > 0) {
          const [startYear, endYear] = rule.decade;
          if (track.year >= startYear && track.year <= endYear) {
            isMatch = true;
          } else {
            isMatch = false; // Must strictly be within range if rule specified decade
          }
        }

        if (isMatch) {
          matchedTracks.push(track);
        }
      }

      if (matchedTracks.length > 0) {
        playlists.push({
          name: `${prefix}${rule.name}`,
          description: `${rule.description || rule.name} • Auto-generated by spotify-local`,
          tracks: matchedTracks,
          trackUris: matchedTracks.map((t) => t.uri),
        });
      }
    }

    return playlists.sort((a, b) => b.tracks.length - a.tracks.length);
  }
}

export const musicSorter = new MusicSorter();
